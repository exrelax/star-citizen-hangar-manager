/**
 * Builds the SVG icon sprites from the single icons in `src/assets/svg-sprites/<set>/*.svg`
 * (`pnpm svg-sprite`):
 *
 * - `src/assets/svg-sprites/<set>.svg`: one `<symbol id="shm-icon-<set>-<name>">` per icon, with
 *   its `viewBox` and shapes only. Each icon is optimized with svgo first (shorter path data, no
 *   comments, sizes or metadata); the license notice is kept once per sprite instead of per icon.
 * - `src/icons/icon-names.ts`: the names of all icons, so the `SvgIcon` component only accepts
 *   existing ones.
 *
 * The output is sorted, so it only changes when the icons do.
 */
import fs from 'node:fs';
import path from 'node:path';
import { optimize } from 'svgo';

const SOURCE = 'src/assets/svg-sprites';
const NAMES_FILE = 'src/icons/icon-names.ts';
/** Kept in each sprite: Font Awesome Free (CC BY 4.0) asks for attribution in the files. */
const LICENSES = {
  fa: 'Font Awesome Free by @fontawesome - https://fontawesome.com License - https://fontawesome.com/license/free Copyright Fonticons, Inc.',
};

function symbolOf(set, name, source) {
  const svg = optimize(source, {
    multipass: true,
    // Keeps the viewBox (it scales the symbol), drops width/height in its favour.
    plugins: [{ name: 'preset-default' }, 'removeDimensions', 'removeXMLNS'],
  }).data;
  const viewBox = /<svg\b[^>]*\bviewBox="([^"]+)"/.exec(svg)?.[1];
  const body = /<svg\b[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg)?.[1];
  if (!viewBox || body === undefined) {
    throw new Error(`${set}/${name}.svg: no <svg> with a viewBox`);
  }
  const shapes = body
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .trim();
  return `<symbol id="shm-icon-${set}-${name}" viewBox="${viewBox}">${shapes}</symbol>`;
}

const sets = fs
  .readdirSync(SOURCE, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const names = {};
for (const set of sets) {
  const files = fs
    .readdirSync(path.join(SOURCE, set))
    .filter((file) => file.endsWith('.svg'))
    .sort();
  names[set] = files.map((file) => file.slice(0, -'.svg'.length));
  const symbols = files.map((file, index) =>
    symbolOf(set, names[set][index], fs.readFileSync(path.join(SOURCE, set, file), 'utf8')),
  );
  const license = LICENSES[set] ? `<!-- ${LICENSES[set]} -->` : '';
  const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${license}${symbols.join('')}</svg>\n`;
  const target = path.join(SOURCE, `${set}.svg`);
  fs.writeFileSync(target, sprite);
  console.log(`${target}: ${files.length} icons, ${sprite.length} bytes`);
}

const lines = [
  '// Generated by scripts/build-icon-sprites.js (`pnpm svg-sprite`) – do not edit.',
  '',
  'export const ICON_NAMES = {',
  ...sets.map((set) => `  ${set}: [${names[set].map((name) => `'${name}'`).join(', ')}],`),
  '} as const;',
  '',
  'export type IconSet = keyof typeof ICON_NAMES;',
  'export type IconName<S extends IconSet = IconSet> = (typeof ICON_NAMES)[S][number];',
  '',
];
fs.mkdirSync(path.dirname(NAMES_FILE), { recursive: true });
fs.writeFileSync(NAMES_FILE, lines.join('\n'));
console.log(`${NAMES_FILE}: ${sets.length} set(s)`);
